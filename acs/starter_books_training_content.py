def _lesson_document(spec: StarterLessonSpec, *, heading_level: int = 1) -> BookDocument:
    blocks = [
        Heading(
            text=spec.title,
            level=heading_level,
            block_id=f"starter-{spec.lesson_id}-heading",
            source_anchor=f"starter:{spec.lesson_id}:heading",
        )
    ]
    blocks.extend(
        Paragraph(
            text=text,
            block_id=f"starter-{spec.lesson_id}-p{index}",
            source_anchor=f"starter:{spec.lesson_id}:p{index}",
        )
        for index, text in enumerate(spec.paragraphs, start=1)
    )
    blocks.extend(
        Exercise(
            fen=START_FEN,
            prompt=question,
            answer_text=answer,
            difficulty="starter",
            block_id=f"starter-{spec.lesson_id}-exercise-{index:02d}",
            source_anchor=f"starter:{spec.lesson_id}:exercise:{index:02d}",
        )
        for index, (question, answer) in enumerate(spec.checks, start=1)
    )
    return BookDocument(
        title=spec.title,
        language=STARTER_CONTENT_LANGUAGE,
        author="Accessible Chess project",
        source_name=f"Accessible Chess starter material: {spec.lesson_id}",
        source_rights=STARTER_CONTENT_RIGHTS,
        blocks=blocks,
    )


def build_starter_materials() -> tuple[BookDocument, ...]:
    """Return 24 standalone, canonical, project-authored tutorial materials."""
    return tuple(_lesson_document(spec) for spec in _LESSONS)


def build_starter_course() -> BookDocument:
    """Return the one-click aggregate course used by the packaged V2 product."""
    blocks = [
        Heading(
            text="Accessible Chess: стартовий курс",
            level=1,
            block_id="starter-course-heading",
            source_anchor="starter:course:heading",
        ),
        Paragraph(
            text=(
                "Офлайн-курс містить 24 українські навчальні модулі та 120 вправ. "
                "Він використовує той самий BookDocument і той самий Training, що й імпортовані книги, "
                "тому доступний без мережі та без ручного пошуку файлів."
            ),
            block_id="starter-course-introduction",
            source_anchor="starter:course:introduction",
        ),
    ]
    for spec in _LESSONS:
        material = _lesson_document(spec, heading_level=2)
        blocks.extend(material.blocks)
    return BookDocument(
        title="Accessible Chess: стартовий курс",
        language=STARTER_CONTENT_LANGUAGE,
        author="Accessible Chess project",
        source_name="Accessible Chess built-in offline starter course",
        source_rights=STARTER_CONTENT_RIGHTS,
        blocks=blocks,
    )


def starter_content_manifest() -> dict[str, object]:
    materials = build_starter_materials()
    return {
        "schema_version": STARTER_CONTENT_VERSION,
        "language": STARTER_CONTENT_LANGUAGE,
        "rights": STARTER_CONTENT_RIGHTS,
        "material_count": len(materials),
        "exercise_count": sum(len(material.exercises()) for material in materials),
        "materials": tuple(
            {
                "material_id": spec.lesson_id,
                "title": spec.title,
                "exercise_count": len(material.exercises()),
            }
            for spec, material in zip(_LESSONS, materials, strict=True)
        ),
    }


